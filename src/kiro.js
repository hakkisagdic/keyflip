// @ts-check
// Kiro surface adapter. Kiro keeps its login in two unrelated places:
//   * CLI: the macOS Keychain services `kirocli:odic:token` and
//     `kirocli:odic:device-registration` (compact JSON, no trailing newline);
//   * IDE: `~/.aws/sso/cache/kiro-auth-token.json`, whose `clientIdHash` names
//     the matching `<hash>.json` registration file next to it.
//
// The two surfaces can share one refresh chain (a refresh in either place may
// rotate the other's token), so a capture stores each one independently and a
// switch writes only the surfaces the bundle actually has.
// Secrets live in 0600 files under <configDir>/surfaces/kiro/<slug>/ (already
// git-ignored by the state repo); meta.json is secret-free. Keychain values are
// never passed on a command line: a small compiled helper reads them on stdin.
import fs from 'fs';
import path from 'path';
import { run as defaultRun } from './exec.js';
import { atomicWrite, writeJsonStable } from './fsutil.js';
import * as profiles from './profiles.js';

const CLI_TOKEN_SVC = 'kirocli:odic:token';
const CLI_REG_SVC = 'kirocli:odic:device-registration';
const SECURITY = '/usr/bin/security';
const PROC_NAMES = ['Kiro', 'kiro_cli_desktop', 'kiro-cli'];

// The helper exists because `security add-generic-password` needs the value in
// argv (visible to every process) and `security -i` splits long lines (~4 KB),
// while a 4 KB Kiro registration is exactly what we must move. SecItemUpdate
// also preserves the item's ACL, so kiro-cli keeps reading its own item.
const HELPER_SOURCE = `// kfkc — generated by keyflip; do not edit.
//   kfkc set <service>   replace the item's data (secret arrives on stdin only)
//   kfkc stat <service>  print byte length + sha256 prefix (value hidden)
//   kfkc cmp <a> <b>     say whether two items hold byte-identical data
#include <CoreFoundation/CoreFoundation.h>
#include <Security/Security.h>
#include <CommonCrypto/CommonDigest.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static char *read_stdin(size_t *out_len) {
  size_t cap = 8192, len = 0;
  char *buf = malloc(cap);
  if (!buf) return NULL;
  for (;;) {
    if (len == cap) {
      cap *= 2;
      buf = realloc(buf, cap);
      if (!buf) return NULL;
    }
    size_t n = fread(buf + len, 1, cap - len, stdin);
    len += n;
    if (n == 0) break;
  }
  if (len && buf[len - 1] == '\\n') len--;
  *out_len = len;
  return buf;
}

static CFTypeRef q_service(const char *service) {
  CFMutableDictionaryRef q = CFDictionaryCreateMutable(kCFAllocatorDefault, 0, &kCFTypeDictionaryKeyCallBacks, &kCFTypeDictionaryValueCallBacks);
  CFDictionarySetValue(q, kSecClass, kSecClassGenericPassword);
  CFDictionarySetValue(q, kSecAttrService, CFStringCreateWithCString(kCFAllocatorDefault, service, kCFStringEncodingUTF8));
  return q;
}

int main(int argc, char **argv) {
  if (argc < 3) { fprintf(stderr, "usage: kfkc set <service> | stat <service> | cmp <a> <b>\\n"); return 2; }
  const char *mode = argv[1];

  if (strcmp(mode, "set") == 0) {
    size_t len = 0;
    char *val = read_stdin(&len);
    if (!val) { fprintf(stderr, "read failed\\n"); return 1; }
    if (len == 0) { fprintf(stderr, "REFUSING to write an empty value\\n"); return 1; }
    CFTypeRef q = q_service(argv[2]);
    CFDataRef data = CFDataCreate(kCFAllocatorDefault, (const UInt8 *)val, (CFIndex)len);
    CFMutableDictionaryRef up = CFDictionaryCreateMutable(kCFAllocatorDefault, 0, &kCFTypeDictionaryKeyCallBacks, &kCFTypeDictionaryValueCallBacks);
    CFDictionarySetValue(up, kSecValueData, data);
    OSStatus st = SecItemUpdate(q, up);
    CFRelease(q); CFRelease(data); CFRelease(up);
    memset(val, 0, len); free(val);
    if (st != noErr) {
      CFStringRef msg = NULL; SecCopyErrorMessageString(st, (void **)&msg);
      char buf[256] = "";
      if (msg) CFStringGetCString(msg, buf, sizeof(buf), kCFStringEncodingUTF8);
      fprintf(stderr, "SecItemUpdate(%s) -> %d %s\\n", argv[2], (int)st, buf);
      return 3;
    }
    printf("set %s (%zu bytes)\\n", argv[2], len);
    return 0;
  }

  if (strcmp(mode, "stat") == 0 || strcmp(mode, "cmp") == 0) {
    int n = (strcmp(mode, "stat") == 0) ? 1 : 2;
    char *vals[2]; size_t lens[2];
    for (int i = 0; i < n; i++) {
      CFTypeRef q = q_service(argv[2 + i]);
      CFMutableDictionaryRef get = (CFMutableDictionaryRef)q;
      CFDictionarySetValue(get, kSecReturnData, kCFBooleanTrue);
      CFDictionarySetValue(get, kSecMatchLimit, kSecMatchLimitOne);
      CFTypeRef out = NULL;
      OSStatus st = SecItemCopyMatching(get, &out);
      if (st != noErr || !out) { fprintf(stderr, "%s: not found/readable (%d)\\n", argv[2 + i], (int)st); return 4; }
      CFDataRef d = (CFDataRef)out;
      lens[i] = (size_t)CFDataGetLength(d);
      vals[i] = malloc(lens[i] + 1);
      CFDataGetBytes(d, CFRangeMake(0, (CFIndex)lens[i]), (UInt8 *)vals[i]);
      CFRelease(d); CFRelease(q);
    }
    if (strcmp(mode, "stat") == 0) {
      unsigned char md[CC_SHA256_DIGEST_LENGTH];
      CC_SHA256((const unsigned char *)vals[0], (CC_LONG)lens[0], md);
      printf("%s bytes=%zu sha=", argv[2], lens[0]);
      for (int i = 0; i < 6; i++) printf("%02x", md[i]);
      printf("\\n");
    } else {
      int same = lens[0] == lens[1] && memcmp(vals[0], vals[1], lens[0]) == 0;
      printf("%s vs %s: %s (%zu/%zu bytes)\\n", argv[2], argv[3], same ? "IDENTICAL" : "DIFFERENT", lens[0], lens[1]);
    }
    for (int i = 0; i < n; i++) { memset(vals[i], 0, lens[i]); free(vals[i]); }
    return 0;
  }
  fprintf(stderr, "unknown mode\\n");
  return 2;
}
`;

function err(message, code) {
  const e = /** @type {any} */ (new Error(message));
  e.code = code || 'KIRO';
  return e;
}

function depsOf(d) {
  d = d || {};
  return {
    run: d.run || defaultRun,
    now: d.now || null,
    helper: d.helper || null,
    cc: d.cc || 'cc',
    kiroCli: d.kiroCli || null,
    running: Array.isArray(d.running) ? d.running : null,
    logLimit: d.logLimit || 20,
  };
}

function nowIso(ctx, deps) {
  if (deps && deps.now) return deps.now();
  if (ctx && typeof ctx.now === 'function') return ctx.now();
  return new Date().toISOString();
}

function normalizeEmail(email) {
  return String(email || '')
    .trim()
    .toLowerCase();
}

function isExpired(iso, atIso) {
  const t = Date.parse(iso || '');
  if (!isFinite(t)) return false; // unknown is not "expired"
  return t <= Date.parse(atIso || new Date().toISOString());
}

function surfaceRoot(ctx) {
  return path.join(ctx.configDir, 'surfaces', 'kiro');
}

function accountDir(ctx, slug) {
  return path.join(surfaceRoot(ctx), slug);
}

function metaPath(ctx, slug) {
  return path.join(accountDir(ctx, slug), 'meta.json');
}

function ideCacheDir(ctx) {
  return path.join(ctx.home, '.aws', 'sso', 'cache');
}

function ideTokenPath(ctx) {
  return path.join(ideCacheDir(ctx), 'kiro-auth-token.json');
}

function readText(file) {
  try {
    return fs.readFileSync(file, 'utf8').replace(/\n$/, '');
  } catch (e) {
    return null;
  }
}

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (e) {
    return null;
  }
}

function readMeta(ctx, slug) {
  const m = readJson(metaPath(ctx, slug));
  return m && typeof m === 'object' && m.name ? m : null;
}

function keychainRead(service, deps) {
  const r = deps.run(SECURITY, ['find-generic-password', '-s', service, '-w'], undefined, { timeoutMs: 10000 });
  if (!r || r.code !== 0) return { ok: false, missing: !!r && r.code === 44 };
  return { ok: true, value: String(r.stdout || '').replace(/\n$/, '') };
}

function parseJson(text) {
  try {
    return JSON.parse(text);
  } catch (e) {
    return null;
  }
}

function readCliRaw(ctx, deps) {
  const t = keychainRead(CLI_TOKEN_SVC, deps);
  if (!t.ok) return { present: false, corrupt: false, missing: t.missing };
  const tok = parseJson(t.value);
  if (!tok || !tok.access_token) return { present: false, corrupt: true, bytes: t.value.length };
  const r = keychainRead(CLI_REG_SVC, deps);
  const regObj = r.ok ? parseJson(r.value) : null;
  return {
    present: true,
    token: t.value,
    tokenObj: tok,
    expiresAt: tok.expires_at || null,
    bytes: Buffer.byteLength(t.value),
    registration: r.ok ? r.value : null,
    registrationObj: regObj,
    registrationBytes: r.ok ? Buffer.byteLength(r.value) : 0,
    registrationUnreadable: !r.ok && !r.missing,
    registrationCorrupt: !!r.ok && !(regObj && regObj.client_id && regObj.client_secret),
  };
}

function validRegistration(text, idKey, secretKey) {
  const obj = text ? parseJson(text) : null;
  return !!(obj && obj[idKey] && obj[secretKey]);
}

function sanitizeHash(hash) {
  const h = String(hash || '');
  if (!/^[A-Za-z0-9._-]{8,128}$/.test(h) || h[0] === '.') return null;
  return h;
}

function readIdeRaw(ctx) {
  const p = ideTokenPath(ctx);
  const raw = readText(p);
  if (raw == null) return { present: false, corrupt: false, missing: true, tokenPath: p };
  const tok = parseJson(raw);
  if (!tok || !tok.accessToken) return { present: false, corrupt: true, tokenPath: p, bytes: raw.length };
  const hash = sanitizeHash(tok.clientIdHash);
  let registration = null;
  let registrationObj = null;
  let registrationPath = null;
  if (hash) {
    registrationPath = path.join(ideCacheDir(ctx), hash + '.json');
    registration = readText(registrationPath);
    registrationObj = registration ? parseJson(registration) : null;
  }
  return {
    present: true,
    token: raw,
    tokenObj: tok,
    expiresAt: tok.expiresAt || null,
    hash: hash,
    bytes: Buffer.byteLength(raw),
    registration: registration,
    registrationObj: registrationObj,
    registrationExpiresAt: (registrationObj && registrationObj.expiresAt) || null,
    registrationBytes: registration ? Buffer.byteLength(registration) : 0,
    registrationUnreadable: !!registrationPath && !registration && fs.existsSync(registrationPath),
    registrationCorrupt:
      !!registration && !(registrationObj && registrationObj.clientId && registrationObj.clientSecret),
    tokenPath: p,
    registrationPath: registrationPath,
  };
}

function parseWhoami(out) {
  const m = /^\s*Email:\s*(\S+)\s*$/im.exec(String(out || ''));
  return m ? normalizeEmail(m[1]) : null;
}

function kiroCliCandidates(ctx) {
  const out = [];
  if (process.env.KEYFLIP_KIRO_CLI) out.push(process.env.KEYFLIP_KIRO_CLI);
  out.push('kiro-cli');
  out.push(path.join(ctx.home, '.local', 'bin', 'kiro-cli'));
  out.push('/Applications/Kiro CLI.app/Contents/MacOS/kiro-cli');
  out.push('/usr/local/bin/kiro-cli');
  out.push('/opt/homebrew/bin/kiro-cli');
  return out;
}

function readWhoami(ctx, deps) {
  const tryOne = function (bin) {
    const r = deps.run(bin, ['user', 'whoami'], undefined, { timeoutMs: 15000 });
    if (r && r.code === 0) {
      const email = parseWhoami(r.stdout);
      if (email) return email;
    }
    return null;
  };
  if (deps.kiroCli) return tryOne(deps.kiroCli);
  const bins = kiroCliCandidates(ctx);
  for (let i = 0; i < bins.length; i++) {
    const r = deps.run(bins[i], ['user', 'whoami'], undefined, { timeoutMs: 15000 });
    if (r && r.error && r.error.code === 'ENOENT') continue;
    if (r && r.code === 0) {
      const email = parseWhoami(r.stdout);
      if (email) return email;
    }
    // Installed but failing (not logged in, expired): further paths are the same binary.
    if (r && !(r.error && r.error.code === 'ENOENT')) return null;
  }
  return null;
}

function runningApps(ctx, deps) {
  if (deps.running) return deps.running.slice();
  if (ctx.platform !== 'darwin') return [];
  const found = [];
  PROC_NAMES.forEach(function (name) {
    const r = deps.run('/usr/bin/pgrep', ['-x', name], undefined, { timeoutMs: 5000 });
    if (r && r.code === 0) found.push(name);
  });
  return found;
}

function helperFailure(h) {
  if (h.reason === 'platform') return 'Keychain writes are macOS-only for now.';
  if (h.reason === 'helper-write') return 'could not write the helper source: ' + (h.detail || 'unknown');
  if (h.reason === 'helper-build')
    return (
      'could not build the Keychain helper (Xcode Command Line Tools: `xcode-select --install`): ' +
      (h.detail || 'unknown')
    );
  return h.detail || h.reason || 'unknown';
}

function sdkCandidates() {
  const dir = '/Library/Developer/CommandLineTools/SDKs';
  let names;
  try {
    names = fs.readdirSync(dir);
  } catch (e) {
    return [];
  }
  return names
    .filter(function (n) {
      return /^MacOSX[0-9.]+\.sdk$/.test(n);
    })
    .sort(function (a, b) {
      return b.localeCompare(a, undefined, { numeric: true });
    })
    .map(function (n) {
      return path.join(dir, n);
    });
}

function compileHelper(runner, cc, src, bin, defaultSdk) {
  const tail = ['-O2', '-o', bin, src, '-framework', 'Security', '-framework', 'CoreFoundation'];
  const attempts = [{ label: null, args: tail }];
  sdkCandidates().forEach(function (sdk) {
    if (defaultSdk && path.resolve(sdk) === path.resolve(defaultSdk)) return;
    attempts.push({
      label: sdk,
      args: ['-O2', '-isysroot', sdk, '-o', bin, src, '-framework', 'Security', '-framework', 'CoreFoundation'],
    });
  });
  let last = null;
  for (let i = 0; i < attempts.length; i++) {
    const r = runner(cc, attempts[i].args);
    if (r && r.code === 0) return { ok: true };
    last = r;
    try {
      fs.rmSync(bin, { force: true });
    } catch (e) {
      /* partial binary */
    }
  }
  return {
    ok: false,
    detail: String((last && (last.stderr || last.stdout)) || '').slice(0, 400),
  };
}

function ensureHelper(ctx, deps) {
  const runner = (deps && deps.run) || defaultRun;
  const cc = (deps && deps.cc) || 'cc';
  if (deps && deps.helper) return { ok: true, path: deps.helper };
  if (ctx.platform !== 'darwin') return { ok: false, reason: 'platform' };
  const dir = path.join(surfaceRoot(ctx), '.bin');
  const src = path.join(dir, 'kfkc.c');
  const bin = path.join(dir, 'kfkc');
  let current = null;
  try {
    current = fs.readFileSync(src, 'utf8');
  } catch (e) {
    /* absent */
  }
  let need = current !== HELPER_SOURCE;
  if (!need) {
    try {
      fs.accessSync(bin, fs.constants.X_OK);
    } catch (e) {
      need = true;
    }
  }
  if (!need) return { ok: true, path: bin };
  try {
    fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
    atomicWrite(src, HELPER_SOURCE, 0o600);
  } catch (e) {
    return { ok: false, reason: 'helper-write', detail: e.message };
  }
  // A CommandLineTools install can pair a newer SDK with a linker that rejects
  // its .tbd files (observed: MacOSX27.0 + ld-1267). Retry against the other
  // installed SDKs rather than fail on a healthy C compiler.
  const sdk = runner('xcrun', ['--show-sdk-path'], undefined, { timeoutMs: 10000 });
  const defaultSdk = sdk && sdk.code === 0 ? String(sdk.stdout || '').trim() : null;
  const built = compileHelper(runner, cc, src, bin, defaultSdk);
  if (!built.ok) return { ok: false, reason: 'helper-build', detail: built.detail };
  try {
    fs.chmodSync(bin, 0o700);
  } catch (e) {
    /* best effort */
  }
  try {
    fs.accessSync(bin, fs.constants.X_OK);
  } catch (e) {
    return { ok: false, reason: 'helper-build', detail: 'compiler produced no executable' };
  }
  return { ok: true, path: bin };
}

function writeKeychain(service, value, ctx, deps) {
  const h = ensureHelper(ctx, deps);
  if (!h.ok) throw err('cannot write the Kiro CLI Keychain item: ' + helperFailure(h), 'KIRO_HELPER');
  const r = deps.run(h.path, ['set', service], value, { timeoutMs: 20000 });
  if (!r || r.code !== 0) {
    throw err(
      'Keychain write failed for ' +
        service +
        ' (SecItemUpdate ' +
        (r ? r.code : '?') +
        '). Log in once with `kiro-cli user login` so the item exists.',
      'KIRO_KEYCHAIN_WRITE',
    );
  }
}

function parseDomain(email) {
  const dom = String(email || '').split('@')[1] || '';
  return profiles.sanitizeName(dom.split('.')[0]);
}

function resolveNamedSlug(ctx, name, email) {
  if (!profiles.isValidName(name)) {
    throw err("invalid account name: '" + name + "' (allowed: A-Z a-z 0-9 . _ -)", 'KIRO_BAD_NAME');
  }
  const prev = readMeta(ctx, name);
  if (prev && prev.email && email && normalizeEmail(prev.email) !== email) {
    throw err(
      "account '" + name + "' already exists for " + prev.email + '; choose another name.',
      'KIRO_NAME_CONFLICT',
    );
  }
  return name;
}

function autoSlug(ctx, email) {
  const base = profiles.sanitizeName(email);
  if (!readMeta(ctx, base)) return base;
  if (normalizeEmail(readMeta(ctx, base).email) === normalizeEmail(email)) return base;
  const dom = parseDomain(email);
  const stem = dom ? base + '-' + dom : base;
  if (!readMeta(ctx, stem)) return stem;
  if (normalizeEmail(readMeta(ctx, stem).email) === normalizeEmail(email)) return stem;
  let n = 1;
  let candidate = stem;
  while (readMeta(ctx, candidate) && normalizeEmail(readMeta(ctx, candidate).email) !== normalizeEmail(email)) {
    n += 1;
    candidate = stem + '-' + n;
  }
  return candidate;
}

function publicAccount(meta) {
  return {
    name: meta.name,
    email: meta.email || '',
    source: meta.source || 'live',
    capturedAt: meta.capturedAt || null,
    cli: meta.cli || null,
    ide: meta.ide || null,
    userId: meta.userId || null,
  };
}

function listAccounts(ctx) {
  let entries;
  try {
    entries = fs.readdirSync(surfaceRoot(ctx), { withFileTypes: true });
  } catch (e) {
    return [];
  }
  const out = [];
  entries.forEach(function (e) {
    if (!e.isDirectory() || e.name[0] === '.') return;
    const meta = readMeta(ctx, e.name);
    if (meta) out.push(publicAccount(Object.assign({}, meta, { name: e.name })));
  });
  out.sort(function (a, b) {
    return a.name.localeCompare(b.name);
  });
  return out;
}

function resolveAccount(ctx, arg) {
  if (arg == null) return null;
  const accounts = listAccounts(ctx);
  const s = String(arg);
  if (/^[0-9]+$/.test(s)) {
    const i = parseInt(s, 10);
    return i >= 1 && i <= accounts.length ? accounts[i - 1].name : null;
  }
  for (let i = 0; i < accounts.length; i++) {
    if (accounts[i].name === s) return s;
  }
  const email = normalizeEmail(s);
  for (let i = 0; i < accounts.length; i++) {
    if (normalizeEmail(accounts[i].email) === email) return accounts[i].name;
  }
  return null;
}

function nameForEmail(ctx, email) {
  const accounts = listAccounts(ctx);
  const want = normalizeEmail(email);
  for (let i = 0; i < accounts.length; i++) {
    if (normalizeEmail(accounts[i].email) === want) return accounts[i].name;
  }
  return null;
}

// Fallback when whoami is unavailable (dead token): identify the outgoing
// bundle by the exact live bytes, so a rotated registration is not lost.
function nameForLive(ctx, liveCli, liveIde) {
  const accounts = listAccounts(ctx);
  for (let i = 0; i < accounts.length; i++) {
    const b = loadBundle(ctx, accounts[i].name);
    if (!b) continue;
    if (liveCli && liveCli.present && b.cli && b.cli.token === liveCli.token) return accounts[i].name;
    if (!(liveCli && liveCli.present) && liveIde && liveIde.present && b.ide && b.ide.token === liveIde.token) {
      return accounts[i].name;
    }
  }
  return null;
}

function loadBundle(ctx, slug) {
  const dir = accountDir(ctx, slug);
  const meta = readMeta(ctx, slug);
  if (!meta) return null;
  const cliToken = readText(path.join(dir, 'cli-token.json'));
  const cliRegRaw = readText(path.join(dir, 'cli-registration.json'));
  const cliRegOk = validRegistration(cliRegRaw, 'client_id', 'client_secret');
  const cliTokObj = cliToken ? parseJson(cliToken) : null;
  const ideToken = readText(path.join(dir, 'ide-token.json'));
  const ideRegRaw = readText(path.join(dir, 'ide-registration.json'));
  const ideRegOk = validRegistration(ideRegRaw, 'clientId', 'clientSecret');
  const ideTokObj = ideToken ? parseJson(ideToken) : null;
  return {
    slug: slug,
    dir: dir,
    meta: meta,
    cli:
      cliToken && cliTokObj && cliTokObj.access_token
        ? {
            token: cliToken,
            expiresAt: cliTokObj.expires_at || null,
            registration: cliRegOk ? cliRegRaw : null,
            bytes: Buffer.byteLength(cliToken),
            registrationBytes: cliRegOk ? Buffer.byteLength(cliRegRaw) : 0,
          }
        : null,
    ide:
      ideToken && ideTokObj && ideTokObj.accessToken
        ? {
            token: ideToken,
            tokenObj: ideTokObj,
            expiresAt: ideTokObj.expiresAt || null,
            hash: sanitizeHash(ideTokObj.clientIdHash),
            registration: ideRegOk ? ideRegRaw : null,
            bytes: Buffer.byteLength(ideToken),
            registrationBytes: ideRegOk ? Buffer.byteLength(ideRegRaw) : 0,
          }
        : null,
  };
}

function summarize(surface) {
  if (!surface) return null;
  return {
    expiresAt: surface.expiresAt || null,
    bytes: surface.bytes,
    registration: !!surface.registration,
    registrationBytes: surface.registrationBytes || 0,
  };
}

function captureAccount(ctx, opts) {
  opts = opts || {};
  const deps = depsOf(opts);
  const surfaces = Array.isArray(opts.surfaces) && opts.surfaces.length ? opts.surfaces.slice() : ['cli', 'ide'];
  const wantCli = surfaces.indexOf('cli') !== -1;
  const wantIde = surfaces.indexOf('ide') !== -1;
  const required = Array.isArray(opts.require) ? opts.require : [];
  if (!wantCli && !wantIde) throw err('nothing to capture (pick cli and/or ide)', 'KIRO_USAGE');

  const cli = opts.cli || (wantCli ? readCliRaw(ctx, deps) : { present: false });
  const ide = opts.ide || (wantIde ? readIdeRaw(ctx) : { present: false });
  const cliOk = wantCli && cli.present && !cli.registrationUnreadable && !cli.registrationCorrupt;
  const ideOk = wantIde && ide.present && !ide.registrationUnreadable && !ide.registrationCorrupt;
  if (wantCli && required.indexOf('cli') !== -1 && !cliOk) {
    throw err(
      cli.corrupt
        ? 'the live Kiro CLI token is unreadable/corrupt; log in with `kiro-cli user login` first.'
        : cli.registrationUnreadable
          ? 'could not read the Kiro CLI device-registration (is the Keychain locked?).'
          : cli.registrationCorrupt
            ? 'the live Kiro CLI device-registration is corrupt; log in with `kiro-cli user login` again.'
            : 'no live Kiro CLI login found in the Keychain. Log in with `kiro-cli user login` first.',
      'KIRO_NO_CLI',
    );
  }
  if (wantIde && required.indexOf('ide') !== -1 && !ideOk) {
    throw err(
      ide.corrupt
        ? 'the Kiro IDE token file is unreadable/corrupt: ' + ideTokenPath(ctx)
        : ide.registrationUnreadable
          ? 'could not read the Kiro IDE registration file for this token.'
          : ide.registrationCorrupt
            ? 'the Kiro IDE registration file is corrupt; sign in to Kiro again.'
            : 'no live Kiro IDE login found (' + ideTokenPath(ctx) + ' is missing). Sign in to Kiro first.',
      'KIRO_NO_IDE',
    );
  }
  if (!cliOk && !ideOk) {
    throw err('no live Kiro CLI or IDE login found. Log in with `kiro-cli user login` first.', 'KIRO_NO_SURFACE');
  }

  let email = normalizeEmail(opts.email);
  if (!email) email = readWhoami(ctx, deps);
  let slug;
  if (opts.name) slug = resolveNamedSlug(ctx, opts.name, email);
  else if (email) slug = autoSlug(ctx, email);
  else {
    throw err(
      'could not detect the Kiro account email (is `kiro-cli user whoami` working?); pass a name: keyflip kiro capture <name>',
      'KIRO_NO_EMAIL',
    );
  }

  const dir = accountDir(ctx, slug);
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  try {
    fs.chmodSync(dir, 0o700);
  } catch (e) {
    /* best effort */
  }

  const captured = { cli: false, ide: false };
  if (cliOk) {
    atomicWrite(path.join(dir, 'cli-token.json'), cli.token, 0o600);
    atomicWrite(path.join(dir, 'cli-registration.json'), cli.registration, 0o600);
    captured.cli = true;
  }
  if (ideOk) {
    atomicWrite(path.join(dir, 'ide-token.json'), ide.token, 0o600);
    atomicWrite(path.join(dir, 'ide-registration.json'), ide.registration, 0o600);
    captured.ide = true;
  }

  const prev = readMeta(ctx, slug) || {};
  const at = nowIso(ctx, deps);
  const meta = {
    schemaVersion: 1,
    name: slug,
    email: email || prev.email || '',
    source: opts.source || 'live',
    capturedAt: prev.capturedAt || at,
    updatedAt: at,
    cli: captured.cli
      ? {
          expiresAt: cli.expiresAt || null,
          bytes: cli.bytes || 0,
          registration: !!cli.registration,
          registrationBytes: cli.registrationBytes || 0,
        }
      : prev.cli || null,
    ide: captured.ide
      ? {
          expiresAt: ide.expiresAt || null,
          hash: ide.hash || null,
          bytes: ide.bytes || 0,
          registration: !!ide.registration,
          registrationBytes: ide.registrationBytes || 0,
          registrationExpiresAt: ide.registrationExpiresAt || null,
        }
      : prev.ide || null,
    userId: prev.userId || null,
  };
  writeJsonStable(metaPath(ctx, slug), meta, 0o600);
  return {
    slug: slug,
    dir: dir,
    meta: publicAccount(meta),
    captured: captured,
    missing: surfaces.filter(function (s) {
      return (s === 'cli' && !captured.cli) || (s === 'ide' && !captured.ide);
    }),
  };
}

function rollbackSnapshot(ctx, bundle, liveCli) {
  const ideTokenFile = ideTokenPath(ctx);
  const ideRegFile =
    bundle && bundle.ide && bundle.ide.hash ? path.join(ideCacheDir(ctx), bundle.ide.hash + '.json') : null;
  return {
    cli: liveCli && liveCli.present ? { token: liveCli.token, registration: liveCli.registration } : null,
    ide: {
      token: { path: ideTokenFile, content: readText(ideTokenFile) },
      registration: ideRegFile ? { path: ideRegFile, content: readText(ideRegFile) } : null,
    },
  };
}

function restoreFile(snapshot) {
  if (!snapshot) return;
  if (snapshot.content == null) {
    try {
      fs.rmSync(snapshot.path, { force: true });
    } catch (e) {
      /* nothing to restore */
    }
  } else atomicWrite(snapshot.path, snapshot.content, 0o600);
}

function rollbackAll(ctx, snap, deps) {
  const failures = [];
  if (snap.cli) {
    try {
      if (snap.cli.token) writeKeychain(CLI_TOKEN_SVC, snap.cli.token, ctx, deps);
      if (snap.cli.registration) writeKeychain(CLI_REG_SVC, snap.cli.registration, ctx, deps);
    } catch (e) {
      failures.push('CLI: ' + e.message);
    }
  }
  try {
    restoreFile(snap.ide.token);
    restoreFile(snap.ide.registration);
  } catch (e) {
    failures.push('IDE: ' + e.message);
  }
  return failures;
}

function switchAccount(ctx, target, opts) {
  opts = opts || {};
  const deps = depsOf(opts);
  const slug = resolveAccount(ctx, target);
  if (!slug) throw err("no such Kiro account: '" + target + "' (see `keyflip kiro list`)", 'KIRO_NOT_FOUND');
  let bundle = loadBundle(ctx, slug);
  if (!bundle) throw err("Kiro account '" + slug + "' has no readable capture (meta.json missing)", 'KIRO_CORRUPT');
  if (!bundle.cli && !bundle.ide) throw err("Kiro account '" + slug + "' has no captured tokens", 'KIRO_CORRUPT');
  if (bundle.cli && (!bundle.cli.registration || (bundle.meta.cli && bundle.meta.cli.registration === false))) {
    throw err(
      "Kiro account '" +
        slug +
        "' was captured without its CLI device-registration. Re-run `keyflip kiro capture " +
        slug +
        '` while logged in.',
      'KIRO_INCOMPLETE',
    );
  }
  if (bundle.ide && !bundle.ide.hash) {
    throw err("Kiro account '" + slug + "' IDE token has no clientIdHash; re-capture it.", 'KIRO_INCOMPLETE');
  }
  if (bundle.ide && (!bundle.ide.registration || (bundle.meta.ide && bundle.meta.ide.registration === false))) {
    throw err(
      "Kiro account '" +
        slug +
        "' was captured without its IDE registration file (" +
        bundle.ide.hash +
        '.json). Re-run `keyflip kiro capture ' +
        slug +
        '`.',
      'KIRO_INCOMPLETE',
    );
  }

  const running = runningApps(ctx, deps);
  // whoami is the only identity source, but running kiro-cli can refresh its own
  // token — so a dry run must not touch it.
  const liveWho = opts.dryRun ? null : readWhoami(ctx, deps);
  const liveCli = readCliRaw(ctx, deps);
  const liveIde = readIdeRaw(ctx);
  const at = nowIso(ctx, deps);
  const plan = {
    target: slug,
    email: bundle.meta.email || '',
    live: {
      email: liveWho || '',
      cli: liveCli.present ? summaryOfRawCli(liveCli, at) : null,
      ide: liveIde.present ? summaryOfRawIde(liveIde, at) : null,
    },
    write: { cli: summarize(bundle.cli), ide: summarize(bundle.ide) },
    running: running,
  };
  if (opts.dryRun) return { dryRun: true, plan: plan };

  if (running.length && !opts.force) {
    throw err(
      'quit ' +
        running.join(' and ') +
        ' before switching (they hold the session), or pass --force. Kiro may rewrite the token on exit.',
      'KIRO_RUNNING',
    );
  }

  // Preserve the outgoing account first (its refresh token may have rotated since capture).
  let capturedOutgoing = null;
  if (liveCli.present || liveIde.present) {
    try {
      const surfaces = [];
      if (liveCli.present) surfaces.push('cli');
      if (liveIde.present) surfaces.push('ide');
      const outName = (liveWho ? nameForEmail(ctx, liveWho) : nameForLive(ctx, liveCli, liveIde)) || undefined;
      capturedOutgoing = captureAccount(ctx, {
        name: outName,
        email: liveWho,
        cli: liveCli,
        ide: liveIde,
        surfaces: surfaces,
        source: 'live-outgoing',
        deps: deps,
      });
    } catch (e) {
      /* non-fatal: the switch is still what the user asked for */
    }
    bundle = loadBundle(ctx, slug) || bundle;
  }

  const snap = rollbackSnapshot(ctx, bundle, liveCli);
  const wrote = [];
  try {
    if (bundle.cli) {
      writeKeychain(CLI_TOKEN_SVC, bundle.cli.token, ctx, deps);
      wrote.push('cli-token');
      writeKeychain(CLI_REG_SVC, bundle.cli.registration, ctx, deps);
      wrote.push('cli-registration');
    }
    if (bundle.ide) {
      atomicWrite(ideTokenPath(ctx), bundle.ide.token, 0o600);
      wrote.push('ide-token');
      atomicWrite(path.join(ideCacheDir(ctx), bundle.ide.hash + '.json'), bundle.ide.registration, 0o600);
      wrote.push('ide-registration');
    }

    // Read back what we wrote — byte-for-byte, the way the owning app would.
    const afterCli = readCliRaw(ctx, deps);
    if (bundle.cli) {
      if (!afterCli.present || afterCli.token !== bundle.cli.token) {
        throw err('post-switch check failed: the CLI token did not read back identically', 'KIRO_VERIFY');
      }
      if (!afterCli.registration || afterCli.registration !== bundle.cli.registration) {
        throw err('post-switch check failed: the CLI registration did not read back identically', 'KIRO_VERIFY');
      }
    }
    if (bundle.ide) {
      const afterIde = readIdeRaw(ctx);
      if (!afterIde.present || afterIde.token !== bundle.ide.token) {
        throw err('post-switch check failed: the IDE token did not read back identically', 'KIRO_VERIFY');
      }
      if (!afterIde.registration || afterIde.registration !== bundle.ide.registration) {
        throw err('post-switch check failed: the IDE registration did not read back identically', 'KIRO_VERIFY');
      }
    }

    // A dead/expired token cannot answer whoami; that is a data problem, not a
    // write problem, so only a POSITIVE mismatch triggers a rollback.
    let verified = false;
    let shownEmail = null;
    // whoami speaks for the CLI login only. An IDE-only capture cannot be checked
    // against it: the CLI is deliberately left on the outgoing account then.
    if (!opts.noVerify && bundle.cli) {
      shownEmail = readWhoami(ctx, deps);
      const want = normalizeEmail(bundle.meta.email);
      if (shownEmail && want && shownEmail !== want) {
        throw err(
          'post-switch check failed: Kiro CLI reports ' +
            shownEmail +
            ', expected ' +
            want +
            '. Nothing was left changed.',
          'KIRO_VERIFY',
        );
      }
      verified = !!(shownEmail && (!want || shownEmail === want));
    }

    // whoami may have refreshed the token; fold the rotated value back into the
    // capture so the bundle never lags its own chain.
    let refreshed = false;
    if (verified) {
      try {
        const fresh = readCliRaw(ctx, deps);
        if (fresh.present && fresh.token !== bundle.cli.token) {
          captureAccount(ctx, {
            name: slug,
            email: bundle.meta.email || shownEmail,
            cli: fresh,
            surfaces: ['cli'],
            source: 'post-switch',
            deps: deps,
          });
          refreshed = true;
        }
      } catch (e) {
        /* keep the successful switch */
      }
    }

    return {
      dryRun: false,
      target: slug,
      plan: plan,
      wrote: wrote,
      verified: verified,
      email: shownEmail || bundle.meta.email || '',
      capturedOutgoing: capturedOutgoing ? capturedOutgoing.slug : null,
      refreshed: refreshed,
    };
  } catch (e) {
    // Nothing to undo when the very first write failed (e.g. the helper could not
    // be built): saying "rolled back" there is misleading.
    const failures = wrote.length ? rollbackAll(ctx, snap, deps) : [];
    const suffix = !wrote.length
      ? ''
      : failures.length
        ? ' Rollback was incomplete: ' + failures.join('; ')
        : ' Changes were rolled back.';
    throw err((e && e.message ? e.message : String(e)) + suffix, (e && e.code) || 'KIRO_SWITCH');
  }
}

function summaryOfRawCli(cli, atIso) {
  return {
    expiresAt: cli.expiresAt || null,
    expired: isExpired(cli.expiresAt, atIso),
    bytes: cli.bytes,
    registration: !!cli.registration,
  };
}

function summaryOfRawIde(ide, atIso) {
  return {
    expiresAt: ide.expiresAt || null,
    expired: isExpired(ide.expiresAt, atIso),
    hash: ide.hash || null,
    bytes: ide.bytes,
    registration: !!ide.registration,
  };
}

function status(ctx, deps) {
  deps = depsOf(deps);
  const at = nowIso(ctx, deps);
  const liveWho = readWhoami(ctx, deps);
  const cli = readCliRaw(ctx, deps);
  const ide = readIdeRaw(ctx);
  return {
    platform: ctx.platform,
    now: at,
    live: {
      email: liveWho || '',
      cli: cli.present ? summaryOfRawCli(cli, at) : null,
      ide: ide.present ? summaryOfRawIde(ide, at) : null,
    },
    running: runningApps(ctx, deps),
    accounts: listAccounts(ctx),
  };
}

function usageLogFiles(ctx) {
  const base = path.join(ctx.home, 'Library', 'Application Support', 'Kiro', 'logs');
  const out = [];
  const walk = function (dir, depth) {
    if (depth > 6) return;
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch (e) {
      return;
    }
    entries.forEach(function (e) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p, depth + 1);
      else if (e.isFile() && e.name === 'q-client.log') {
        try {
          out.push({ path: p, mtime: fs.statSync(p).mtimeMs });
        } catch (e2) {
          /* skip */
        }
      }
    });
  };
  walk(base, 0);
  out.sort(function (a, b) {
    return b.mtime - a.mtime;
  });
  return out;
}

function parseUsageLine(line) {
  const i = String(line || '').indexOf('{');
  if (i === -1) return null;
  const top = parseJson(String(line).slice(i));
  if (!top) return null;
  let out = top.output;
  if (typeof out === 'string') out = parseJson(out);
  if (!out || typeof out !== 'object' || !Array.isArray(out.usageBreakdownList)) return null;
  const b = out.usageBreakdownList[0];
  if (!b || typeof b.currentUsageWithPrecision !== 'number') return null;
  return {
    userId: (out.userInfo && out.userInfo.userId) || null,
    current: b.currentUsageWithPrecision,
    limit: typeof b.usageLimitWithPrecision === 'number' ? b.usageLimitWithPrecision : null,
    overage: typeof b.currentOveragesWithPrecision === 'number' ? b.currentOveragesWithPrecision : null,
    unit: b.unit || null,
    resetAt: b.nextDateReset || out.nextDateReset || null,
    subscriptionType: (out.subscriptionInfo && out.subscriptionInfo.type) || null,
  };
}

function latestUsage(ctx, deps) {
  deps = depsOf(deps);
  const files = usageLogFiles(ctx).slice(0, deps.logLimit);
  for (let i = 0; i < files.length; i++) {
    let text;
    try {
      text = fs.readFileSync(files[i].path, 'utf8');
    } catch (e) {
      continue;
    }
    const lines = text.split('\n');
    let found = null;
    for (let j = 0; j < lines.length; j++) {
      const u = parseUsageLine(lines[j]);
      if (u) found = u;
    }
    if (found) {
      found.seenAt = files[i].mtime ? new Date(files[i].mtime).toISOString() : null;
      return found;
    }
  }
  return null;
}

function usage(ctx, arg, opts) {
  const deps = depsOf(opts);
  const u = latestUsage(ctx, deps);
  let account = null;
  if (arg != null) {
    const slug = resolveAccount(ctx, arg);
    if (!slug) throw err("no such Kiro account: '" + arg + "'", 'KIRO_NOT_FOUND');
    const meta = readMeta(ctx, slug);
    account = meta ? publicAccount(Object.assign({}, meta, { name: slug })) : null;
  }
  return {
    usage: u,
    account: account,
    attributed: !!(u && account && account.userId && u.userId === account.userId),
  };
}

function decodeLegacyJson(text) {
  if (!text) return null;
  const s = String(text).trim();
  let obj = parseJson(s);
  if (obj) return { text: s, obj: obj };
  if (/^[0-9a-f]+$/i.test(s) && s.length % 2 === 0) {
    try {
      const decoded = Buffer.from(s, 'hex').toString('utf8');
      obj = parseJson(decoded);
      if (obj) return { text: decoded, obj: obj };
    } catch (e) {
      /* not hex */
    }
  }
  return null;
}

function importLegacy(ctx, slugs, opts) {
  opts = opts || {};
  const deps = depsOf(opts);
  if (!Array.isArray(slugs) || !slugs.length) {
    throw err('pass one or more captured slugs (e.g. keyflip kiro import alice bob)', 'KIRO_USAGE');
  }
  const imported = [];
  const skipped = [];
  slugs.forEach(function (raw) {
    const slug = String(raw);
    if (!profiles.isValidName(slug)) {
      skipped.push({ name: slug, reason: 'invalid-name' });
      return;
    }
    if (fs.existsSync(accountDir(ctx, slug)) && !opts.force) {
      skipped.push({ name: slug, reason: 'already-exists' });
      return;
    }
    const svc = 'keyflip:surface:kiro:' + slug + ':';
    const ideSvc = 'keyflip:surface:kiro-ide:' + slug + ':';
    const t = keychainRead(svc + 'token', deps);
    const r = keychainRead(svc + 'device-registration', deps);
    const it = keychainRead(ideSvc + 'token', deps);
    const ir = keychainRead(ideSvc + 'device-registration', deps);
    if (!t.ok && !it.ok) {
      skipped.push({ name: slug, reason: 'no-legacy-capture' });
      return;
    }
    const cliTok = t.ok ? decodeLegacyJson(t.value) : null;
    const cliReg = r.ok ? decodeLegacyJson(r.value) : null;
    const ideTok = it.ok ? decodeLegacyJson(it.value) : null;
    const ideReg = ir.ok ? decodeLegacyJson(ir.value) : null;
    if ((t.ok && !cliTok) || (r.ok && !cliReg) || (it.ok && !ideTok) || (ir.ok && !ideReg)) {
      skipped.push({ name: slug, reason: 'corrupt-legacy-capture' });
      return;
    }
    const dir = accountDir(ctx, slug);
    fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
    try {
      fs.chmodSync(dir, 0o700);
    } catch (e) {
      /* best effort */
    }
    if (cliTok) atomicWrite(path.join(dir, 'cli-token.json'), cliTok.text, 0o600);
    if (cliReg) atomicWrite(path.join(dir, 'cli-registration.json'), cliReg.text, 0o600);
    if (ideTok) atomicWrite(path.join(dir, 'ide-token.json'), ideTok.text, 0o600);
    if (ideReg) atomicWrite(path.join(dir, 'ide-registration.json'), ideReg.text, 0o600);
    const at = nowIso(ctx, deps);
    const prev = readMeta(ctx, slug) || {};
    const meta = {
      schemaVersion: 1,
      name: slug,
      email: prev.email || '',
      source: 'legacy-keychain',
      capturedAt: at,
      updatedAt: at,
      cli: cliTok
        ? {
            expiresAt: cliTok.obj.expires_at || null,
            bytes: Buffer.byteLength(cliTok.text),
            registration: !!cliReg,
            registrationBytes: cliReg ? Buffer.byteLength(cliReg.text) : 0,
          }
        : prev.cli || null,
      ide: ideTok
        ? {
            expiresAt: ideTok.obj.expiresAt || null,
            hash: sanitizeHash(ideTok.obj.clientIdHash),
            bytes: Buffer.byteLength(ideTok.text),
            registration: !!ideReg,
            registrationBytes: ideReg ? Buffer.byteLength(ideReg.text) : 0,
            registrationExpiresAt: (ideReg && ideReg.obj.expiresAt) || null,
          }
        : prev.ide || null,
      userId: prev.userId || null,
    };
    writeJsonStable(metaPath(ctx, slug), meta, 0o600);
    imported.push(publicAccount(meta));
  });
  return { imported: imported, skipped: skipped };
}

function removeAccount(ctx, arg, opts) {
  opts = opts || {};
  const slug = resolveAccount(ctx, arg);
  if (!slug) throw err("no such Kiro account: '" + arg + "'", 'KIRO_NOT_FOUND');
  if (!opts.force) {
    throw err("refusing to delete '" + slug + "' without --force (removes its captured tokens)", 'KIRO_CONFIRM');
  }
  fs.rmSync(accountDir(ctx, slug), { recursive: true, force: true });
  return { removed: slug };
}

